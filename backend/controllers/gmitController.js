// GET gmit data (admin)
const getGMIT = async (req, res) => {
  try {
    let gmit = await GMIT.findOne();
    if (!gmit) {
      gmit = await GMIT.create(defaultGMIT).catch(() => defaultGMIT);
    }
    res.json(gmit);
  } catch (err) {
    res.status(500).json({ error: err.message });
  }
};

// GET gmit data publik (hanya yang aktif/tersimpan)
const getPublicGMIT = async (req, res) => {
  try {
    let gmit = await GMIT.findOne();
    if (!gmit) {
      gmit = await GMIT.create(defaultGMIT).catch(() => defaultGMIT);
    }
    // Return only public content
    const publicData = {
      portugis: gmit.portugis,
      belanda: gmit.belanda,
      jepang: gmit.jepang,
      pragmit: gmit.pragmit,
      modern: gmit.modern,
      customGMITSections: gmit.customGMITSections || [],
      contentGMIT: gmit.contentGMIT || {}
    };
    res.json(publicData);
  } catch (err) {
    res.status(500).json({ error: err.message });
  }
};

// CREATE/UPDATE gmit data (admin)
const saveGMIT = async (req, res) => {
  try {
    const {
      portugis, belanda, jepang, pragmit, modern,
      customGMITSections, contentGMIT
    } = req.body;

    let gmit = await GMIT.findOne();

    if (gmit) {
      // Update existing
      gmit.portugis = portugis;
      gmit.belanda = belanda;
      gmit.jepang = jepang;
      gmit.pragmit = pragmit;
      gmit.modern = modern;
      gmit.customGMITSections = customGMITSections || [];
      gmit.contentGMIT = contentGMIT || {};
      await gmit.save();
    } else {
      // Create new
      gmit = new GMIT({
        portugis,
        belanda,
        jepang,
        pragmit,
        modern,
        customGMITSections: customGMITSections || [],
        contentGMIT: contentGMIT || {}
      });
      await gmit.save();
    }

    res.json({ message: 'Data GMIT berhasil disimpan', gmit });
  } catch (err) {
    res.status(500).json({ error: err.message });
  }
};

// DELETE custom gmit section (admin)
const deleteCustomGMITSection = async (req, res) => {
  try {
    const { sectionId } = req.params;

    const gmit = await GMIT.findOne();
    if (!gmit) {
      return res.status(404).json({ error: 'Data GMIT tidak ditemukan' });
    }

    // Remove from custom sections array
    gmit.customGMITSections = gmit.customGMITSections.filter(
      s => s.id !== sectionId
    );

    // Remove from content map
    if (gmit.contentGMIT && gmit.contentGMIT[sectionId]) {
      delete gmit.contentGMIT[sectionId];
    }

    await gmit.save();

    res.json({ message: 'Periode berhasil dihapus', gmit });
  } catch (err) {
    res.status(500).json({ error: err.message });
  }
};

